/**
 * GET /admin/dashboard
 * Affiche le dashboard administrateur avec statistiques
 */
router.get(
  "/admin/dashboard",
  isLoggedIn,
  checkRoles(["admin", "super-admin"]),
  catchAsync(async (req, res) => {
    const { InstitutionEnrollment, InstitutionCourse } = require('../../programs/institution/models');
    const VisitorMessage = require('../../shared/models/visitorMessage');

    const [
      totalUsers, totalAdmins, totalLearners, verifiedUsers,
      institutions, totalInstitutionStudents, unreadMessages
    ] = await Promise.all([
      User.countDocuments(),
      User.countDocuments({ role: { $in: ["admin", "super-admin"] } }),
      User.countDocuments({ role: "user" }),
      User.countDocuments({ isVerified: true }),
      Institution.find({ isActive: true }).select('name').sort({ name: 1 }),
      User.countDocuments({ institutionId: { $ne: null } }),
      VisitorMessage.countDocuments({ isRead: false })
    ]);

    const institutionIds = institutions.map(i => i._id);

    // Per-institution: count enrolled students and courses
    const [enrollmentCounts, courseCounts] = await Promise.all([
      InstitutionEnrollment.aggregate([
        { $match: { institutionId: { $in: institutionIds } } },
        { $group: { _id: '$institutionId', count: { $sum: 1 } } }
      ]),
      InstitutionCourse.aggregate([
        { $match: { institutionId: { $in: institutionIds } } },
        { $group: { _id: '$institutionId', count: { $sum: 1 } } }
      ])
    ]);

    const enrollCountMap = Object.fromEntries(enrollmentCounts.map(r => [r._id.toString(), r.count]));
    const courseCountMap  = Object.fromEntries(courseCounts.map(r => [r._id.toString(), r.count]));

    const institutionStats = institutions.map(inst => ({
      institution:  inst,
      studentCount: enrollCountMap[inst._id.toString()] || 0,
      courseCount:  courseCountMap[inst._id.toString()]  || 0
    }));

    // Enrollments in the last 6 months (monthly buckets via InstitutionEnrollment.createdAt)
    const sixMonthsAgo = new Date();
    sixMonthsAgo.setMonth(sixMonthsAgo.getMonth() - 6);

    const recentEnrollments = await InstitutionEnrollment.aggregate([
      { $match: { createdAt: { $gte: sixMonthsAgo } } },
      { $group: {
          _id: {
            year:  { $year:  '$createdAt' },
            month: { $month: '$createdAt' }
          },
          count: { $sum: 1 }
      }},
      { $sort: { '_id.year': 1, '_id.month': 1 } }
    ]);

    res.render("admin/dashboard", {
      stats: { totalUsers, totalAdmins, totalLearners, verifiedUsers },
      institutionStats,
      recentEnrollments,
      totalInstitutions: institutions.length,
      totalInstitutionStudents,
      unreadMessages
    });
  })
);

/**
 * GET /admin/users
 * Affiche la liste des utilisateurs avec filtres et recherche
 */
router.get(
  "/admin/users",
  isLoggedIn,
  checkRoles(["admin", "super-admin"]),
  catchAsync(async (req, res) => {
    const page = parseInt(req.query.page) || 1;
    const limit = 20;
    const skip = (page - 1) * limit;

    // Filtres
    const roleFilter = req.query.role || null;
    const verifiedFilter = req.query.verified !== undefined ? req.query.verified === 'true' : null;
    const searchQuery = req.query.search || '';
    const institutionFilter = req.query.institutionId || null;

    // Construction de la query
    let query = {};

    if (roleFilter) query.role = roleFilter;
    if (verifiedFilter !== null) query.isVerified = verifiedFilter;
    if (institutionFilter) query.institutionId = institutionFilter;

    if (searchQuery) {
      query.$or = [
        { name:     { $regex: searchQuery, $options: 'i' } },
        { surname:  { $regex: searchQuery, $options: 'i' } },
        { username: { $regex: searchQuery, $options: 'i' } },
        { email:    { $regex: searchQuery, $options: 'i' } }
      ];
    }

    // Récupération des utilisateurs + institution name if filtered
    const [users, totalUsers, allInstitutions, activeInstitution] = await Promise.all([
      User.find(query).sort({ createdAt: -1 }).skip(skip).limit(limit),
      User.countDocuments(query),
      Institution.find({ isActive: true }).select('name _id').sort({ name: 1 }),
      institutionFilter ? Institution.findById(institutionFilter).select('name') : Promise.resolve(null)
    ]);

    const totalPages = Math.ceil(totalUsers / limit);

    // Statistiques pour les filtres
    const stats = {
      total: await User.countDocuments(),
      admins: await User.countDocuments({ role: { $in: ["admin", "super-admin"] } }),
      learners: await User.countDocuments({ role: "user" }),
      verified: await User.countDocuments({ isVerified: true }),
      unverified: await User.countDocuments({ isVerified: false })
    };

    res.render("admin/users/list", {
      users,
      currentPage: page,
      totalPages,
      totalUsers,
      stats,
      allInstitutions,
      activeInstitution,
      filters: {
        role: roleFilter,
        verified: verifiedFilter,
        search: searchQuery,
        institutionId: institutionFilter
      }
    });
  })
);


/**
 * POST /reset/:token
 * Traite le changement de mot de passe
 */
router.post("/reset/:token", catchAsync(async (req, res) => {
  const user = await User.findOne({
    resetPasswordToken: req.params.token,
    resetPasswordExpires: { $gt: Date.now() }
  });

  if (!user) {
    req.flash("error", "Le lien de réinitialisation est invalide ou a expiré.");
    return res.redirect("/forgot-password");
  }

  if (req.body.password !== req.body.confirm) {
    req.flash("error", "Les mots de passe ne correspondent pas.");
    return res.redirect("back");
  }

  await user.setPassword(req.body.password);

  user.resetPasswordToken = undefined;
  user.resetPasswordExpires = undefined;

  await user.save();

  // login the user
  req.login(user, (err) => {
    if (err) {
      req.flash("error", "Mot de passe changé, mais erreur de connexion automatique. Veuillez vous connecter.");
      return res.redirect("/login");
    }
    req.flash("success", "Votre mot de passe a été modifié avec succès !");

    // Save session before redirect
    req.session.save(() => {
      res.redirect("/");
    });
  });
}));


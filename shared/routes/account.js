/**
 * PUT /admin/users/:id
 * Met à jour un utilisateur
 */
router.put(
  "/admin/users/:id",
  isLoggedIn,
  checkRoles(["admin", "super-admin"]),
  catchAsync(async (req, res) => {
    const { name, surname, username, email, gender, phoneNumber, role, isVerified, imageUrl, about, englishLevel, institutionId } = req.body;

    const user = await User.findById(req.params.id);

    if (!user) {
      req.flash("error", "Utilisateur non trouvé");
      return res.redirect("/admin/users");
    }

    // Vérifier si le username ou email existe déjà (sauf pour l'utilisateur actuel)
    if (username && username !== user.username) {
      const existingUser = await User.findOne({ username, _id: { $ne: req.params.id } });
      if (existingUser) {
        req.flash("error", "Ce nom d'utilisateur est déjà utilisé");
        return res.redirect(`/admin/users/${req.params.id}/edit`);
      }
    }

    if (email && email !== user.email) {
      const existingUser = await User.findOne({ email, _id: { $ne: req.params.id } });
      if (existingUser) {
        req.flash("error", "Cette adresse email est déjà utilisée");
        return res.redirect(`/admin/users/${req.params.id}/edit`);
      }
    }

    // Mise à jour des champs
    if (name) user.name = name;
    if (surname) user.surname = surname;
    if (username) user.username = username;
    if (email) user.email = email.toLowerCase();
    if (gender) user.gender = gender;
    if (phoneNumber !== undefined) user.phoneNumber = phoneNumber || undefined;
    if (role) user.role = role;
    // Handle checkbox: if checked, value is 'true', if unchecked, it's undefined
    user.isVerified = req.body.isVerified === 'true' || req.body.isVerified === true;
    if (imageUrl !== undefined) user.imageUrl = imageUrl;
    if (about !== undefined) user.about = about;
    if (englishLevel !== undefined) user.englishLevel = englishLevel;
    // institutionId: empty string means "remove", a valid id means "assign"
    if (institutionId !== undefined) {
      user.institutionId = institutionId || null;
    }

    await user.save();

    req.flash("success", `Le profil de ${user.name} ${user.surname} a été mis à jour avec succès`);
    res.redirect(`/admin/users/${req.params.id}/edit`);
  })
);


/**
 * POST /createaccount
 * Crée un compte utilisateur de base
 * Note: Pas de middleware pour permettre la création du premier compte admin
 * Les enrôlements dans les programmes se font séparément
 */
router.post(
  "/createaccount",
  catchAsync(async (req, res) => {
    // Support both direct fields and nested account object
    const accountData = req.body.account || req.body;
    let { name, surname, username, email, gender, phoneNumber, password, defP } = accountData;

    // Validation: Check required fields (except password which can be auto-generated)
    if (!name || !surname || !username || !email || !gender) {
      req.flash("error", "Veuillez remplir tous les champs obligatoires");
      return res.redirect(req.get("Referrer") || "/");
    }

    let isAutoGeneratedPassword = false;

    // Handle Password Logic
    if (!password) {
      // Generate random password if not provided
      const length = 10;
      const charset = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*";
      password = "";
      for (let i = 0, n = charset.length; i < length; ++i) {
        password += charset.charAt(Math.floor(Math.random() * n));
      }
      // Ensure it meets complexity requirements (hacky fix usually redundant with strong charset but safe)
      password += "A1a";
      defP = password;
      isAutoGeneratedPassword = true;
    } else {
      // Validation: password confirmation
      if (password !== defP) {
        req.flash("error", "Les mots de passe ne correspondent pas");
        return res.redirect(req.get("Referrer") || "/");
      }

      // Validation: password strength (minimum 6 characters)
      if (password.length < 6) {
        req.flash("error", "Le mot de passe doit contenir au moins 6 caractères");
        return res.redirect(req.get("Referrer") || "/");
      }
    }

    // Check if username already exists
    const existingUser = await User.findOne({ $or: [{ username }, { email }] });
    if (existingUser) {
      if (existingUser.username === username) {
        req.flash("error", "Ce nom d'utilisateur est déjà pris");
      } else {
        req.flash("error", "Cette adresse email est déjà utilisée");
      }
      return res.redirect(req.get("Referrer") || "/");
    }

    // Determine role: if no admin exists, allow creating admin, otherwise use provided role or default to "user"
    const adminCount = await User.countDocuments({ role: { $in: ["admin", "super-admin"] } });
    let userRole = accountData.role || "user";

    // If no admin exists, allow setting role to admin (for first admin creation)
    if (adminCount === 0 && (userRole === "admin" || userRole === "super-admin")) {
      // Allow creating admin if no admin exists
    } else if (adminCount === 0) {
      // If no admin exists and no role specified, default to admin for first user
      userRole = "admin";
    } else if (userRole !== "user" && userRole !== "admin" && userRole !== "super-admin" && userRole !== "account-manager") {
      // If admins exist and invalid role specified, default to user
      userRole = "user";
    }

    // Generate Activation Token
    const activationToken = crypto.randomBytes(32).toString("hex");
    const activationExpires = Date.now() + 24 * 60 * 60 * 1000; // 24 hours

    // Resolve institution if provided
    const institutionId = accountData.institutionId || null;
    if (institutionId) {
      const inst = await Institution.findById(institutionId);
      if (!inst) {
        req.flash("error", "Institution introuvable.");
        return res.redirect(req.get("Referrer") || "/");
      }
    }

    // Create User object
    const user = new User({
      name,
      surname,
      username,
      email,
      gender,
      phoneNumber: phoneNumber || undefined,
      role: userRole,
      isVerified: adminCount === 0 ? true : false, // Auto-verify first admin
      activationToken,
      activationExpires,
      institutionId: institutionId || null
    });

    // Register user with password (passport-local-mongoose)
    const registeredUser = await User.register(user, password);

    // Send Activation Email if not first admin (first admin is auto verified)
    if (adminCount > 0) {
      try {
        // Construct activation URL
        const activationUrl = `${getBaseUrl(req)}/user/activate/${activationToken}`;

        await new Emailer(user, activationUrl).sendActivationEmail(password);

        req.flash(
          "success",
          `Compte créé avec succès ! Un email d'activation a été envoyé à ${email} avec le mot de passe.`
        );
      } catch (err) {
        console.error("Email send error:", err);
        req.flash(
          "warning",
          `Compte créé, mais impossible d'envoyer l'email d'activation. Mot de passe: ${password}`
        );
      }
    } else {
      req.flash(
        "success",
        `Compte ADMIN créé avec succès pour ${registeredUser.surname} ${registeredUser.name} (${registeredUser.email})`
      );
    }

    // Redirect to admin users list or creation page
    const returnTo = req.body.returnTo || "/admin/users/create";

    req.session.save((err) => {
      if (err) console.error("Session save error:", err);
      res.redirect(returnTo);
    });
  })
);

